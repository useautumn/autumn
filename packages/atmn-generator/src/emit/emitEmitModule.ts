import type {
	CollectionBranchMeta,
	NestedFixtureMeta,
	SingletonMeta,
} from "../collections";
import { schemaDefaults, schemaPaths } from "../fuzz/schemaPaths";
import { deprecatedFieldsOf, type Overlay } from "../overlay/overlay";
import {
	catalogUpdateSchema,
	collectionItemSchema,
	type OpenApiDocument,
	requestBodySchema,
} from "../spec/loadSpec";
import { resolveRef } from "../spec/resolveRef";
import { branchBodySchema } from "./emitCollection";
import { singletonFields } from "./emitSingleton";
import { fixtureKeys, requiredFixturePaths } from "./fixtureKeys";

const GENERATED_HEADER = `// Generated by @autumn/atmn-generator from packages/openapi/openapi-internal.yml.
// Do not edit — run \`bun generate\` in packages/atmn-generator instead.
`;

/** The registration minus fixture-only extras like `typeName`. */
type EmittedCollection = {
	readonly builder: string;
	readonly idField: string;
	readonly responseIdField: string;
	readonly historyKey?: string;
	readonly pull: boolean;
	readonly branches?: readonly CollectionBranchMeta[];
};

/**
 * The CLI's copy of COLLECTIONS: what `atmn pull` needs to turn a server row
 * into fixture source. Keys come from the same walk that emits the fixture
 * type, so the two can never disagree.
 */
export const emitEmitModule = ({
	spec,
	overlay,
	collections,
	nested,
	singletons,
}: {
	spec: OpenApiDocument;
	overlay: Overlay;
	collections: Readonly<Record<string, EmittedCollection>>;
	nested: Readonly<Record<string, NestedFixtureMeta>>;
	singletons: Readonly<Record<string, SingletonMeta>>;
}): string => {
	const root = spec as never;
	const allPaths = schemaPaths({
		schema: catalogUpdateSchema({ spec }),
		root: spec as never,
		overlay,
	});
	const allDefaults = schemaDefaults({
		schema: catalogUpdateSchema({ spec }),
		root: spec as never,
		overlay,
	});
	const defaultsUnder = (prefix: string): Record<string, unknown> =>
		Object.fromEntries(
			[...allDefaults]
				.filter(([path]) => path.startsWith(prefix))
				.map(([path, value]) => [path.slice(prefix.length), value] as const)
				.sort(([left], [right]) => left.localeCompare(right)),
		);
	const lines: string[] = [
		GENERATED_HEADER,
		'import type { CollectionSpec, SingletonSpec } from "./emitRuntime";',
		"",
		"export const COLLECTIONS: Readonly<Record<string, CollectionSpec>> = {",
	];
	for (const [name, meta] of Object.entries(collections)) {
		const keys = fixtureKeys({
			schema: collectionItemSchema({ spec, collection: name }),
			overlay,
			collection: name,
		});
		const prefix = `${name}.`;
		const paths = [...allPaths.keys()]
			.filter((path) => path.startsWith(prefix))
			.map((path) => path.slice(prefix.length))
			.sort();
		lines.push(`\t${name}: {`);
		lines.push(`\t\tbuilder: ${JSON.stringify(meta.builder)},`);
		lines.push(`\t\tidField: ${JSON.stringify(meta.idField)},`);
		lines.push(`\t\tresponseIdField: ${JSON.stringify(meta.responseIdField)},`);
		lines.push(`\t\tkeys: ${JSON.stringify(keys)},`);
		lines.push(
			`\t\trequired: ${JSON.stringify(
				requiredFixturePaths({
					schema: collectionItemSchema({ spec, collection: name }),
					root: spec as never,
					overlay,
					collection: name,
				}),
			)},`,
		);
		lines.push(`\t\tpaths: ${JSON.stringify(paths)},`);
		lines.push(`\t\tdefaults: ${JSON.stringify(defaultsUnder(prefix))},`);
		if (meta.historyKey !== undefined)
			lines.push(`\t\thistoryKey: ${JSON.stringify(meta.historyKey)},`);
		lines.push(`\t\tpull: ${meta.pull},`);
		lines.push(
			`\t\tdeprecated: ${JSON.stringify(deprecatedFieldsOf({ overlay, collection: name }))},`,
		);
		if (meta.branches) {
			const itemSchema = collectionItemSchema({ spec, collection: name });
			const branches = meta.branches.map((branch) => {
				const branchPrefix = `${prefix}${branch.key}.`;
				return {
					builder: branch.builder,
					key: branch.key,
					idField: branch.idField,
					keys: fixtureKeys({
						schema: branchBodySchema({ schema: itemSchema, key: branch.key }),
						overlay,
						collection: name,
					}),
					required: requiredFixturePaths({
						schema: branchBodySchema({ schema: itemSchema, key: branch.key }),
						root: spec as never,
						overlay,
						collection: name,
					}),
					paths: [...allPaths.keys()]
						.filter((path) => path.startsWith(branchPrefix))
						.map((path) => path.slice(branchPrefix.length))
						.sort(),
					defaults: defaultsUnder(branchPrefix),
				};
			});
			lines.push(`\t\tbranches: ${JSON.stringify(branches)},`);
		}
		lines.push("\t},");
	}
	lines.push("};");
	lines.push("");
	lines.push(
		"/** One object per config, PATCH semantics: what each key is on the wire and its default. */",
	);
	lines.push(
		`export const SINGLETONS: Readonly<Record<string, SingletonSpec>> = ${JSON.stringify(
			Object.fromEntries(
				Object.entries(singletons).map(([name, meta]) => {
					const body = requestBodySchema({ spec, path: meta.operationPath });
					const schema = body.properties?.[meta.wireKey];
					if (!schema)
						throw new Error(
							`\`${meta.wireKey}\` is not on the ${meta.operationPath} body.`,
						);
					return [
						name,
						{
							wireKey: meta.wireKey,
							fields: singletonFields({
								name,
								schema: resolveRef({ schema, root }) ?? schema,
								overlay,
							}),
						},
					];
				}),
			),
		)};`,
	);
	lines.push("");
	lines.push(
		"/** Fixtures nested in a collection item: builder, id field, and where they live. */",
	);
	lines.push(
		`export const NESTED_FIXTURES: Readonly<Record<string, { builder: string; idField: string; parent: string; path: string }>> = ${JSON.stringify(
			Object.fromEntries(
				Object.entries(nested).map(([name, meta]) => [
					name,
					{
						builder: meta.builder,
						idField: meta.idField,
						parent: meta.parent,
						path: meta.path,
					},
				]),
			),
		)};`,
	);
	return `${lines.join("\n")}\n`;
};
