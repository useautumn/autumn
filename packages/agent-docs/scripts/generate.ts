import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import config, { agents } from "../agent-docs.config.js";
import type { Source } from "../src/config/types.js";
import { composeDocument } from "../src/translate/composeDocument.js";
import { composeSkill } from "../src/translate/composeSkill.js";
import { composeSources } from "../src/translate/composeSources.js";
import { toMcpResource } from "../src/translate/formats/mcpResource.js";
import { toSkill } from "../src/translate/formats/skill.js";
import type { McpResource, Skill } from "../src/translate/formats/types.js";
import { docsPageToMarkdown } from "../src/translate/ingest/docsPage.js";
import { writePublicSkills } from "./publicSkills.js";

// Build-time translation: read canonical docs (+ transitional legacy markdown),
// emit self-contained TS artifacts so consumers need no runtime fs access, plus
// readable rendered .md/SKILL.md for inspection.
const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = resolve(here, "../../../apps/docs/mintlify");
const legacyRoot = resolve(here, "../../mcp/src/resources-v2");
const contentRoot = resolve(here, "../content");

const readSource = (source: Source): string => {
	if (source.type === "docs") {
		const text = readFileSync(resolve(docsRoot, source.page), "utf8");
		return docsPageToMarkdown({ path: source.page, text });
	}
	return readFileSync(resolve(legacyRoot, source.file), "utf8");
};

const headingAnchor = (heading: string): string =>
	heading
		.toLowerCase()
		.replace(/[^a-z0-9\s-]/g, "")
		.trim()
		.replace(/\s+/g, "-");

// `#anchor` slices one section: its heading through to the next heading of the
// same or higher level. Build fails on an anchor that matches no heading.
const sliceSection = ({
	markdown,
	anchor,
	url,
}: {
	markdown: string;
	anchor: string;
	url: string;
}): string => {
	const lines = markdown.split("\n");
	const headingAt = (line: string) => /^(#{1,6})\s+(.*)$/.exec(line);
	const start = lines.findIndex((line) => {
		const heading = headingAt(line);
		return heading && headingAnchor(heading[2] ?? "") === anchor;
	});
	if (start === -1) {
		throw new Error(`No heading matches anchor "#${anchor}" in ${url}`);
	}
	const level = (headingAt(lines[start] ?? "")?.[1] ?? "#").length;
	const end = lines.findIndex((line, index) => {
		if (index <= start) return false;
		const heading = headingAt(line);
		return Boolean(heading && (heading[1]?.length ?? 6) <= level);
	});
	return lines.slice(start, end === -1 ? undefined : end).join("\n");
};

// `<docs url="/documentation/..." />` → translated docs page (with its title).
const resolveDocs = (url: string): string => {
	const [path = "", anchor] = url.split("#");
	const page = `${path.replace(/^\//, "")}.mdx`;
	const markdown = docsPageToMarkdown({
		path: page,
		text: readFileSync(resolve(docsRoot, page), "utf8"),
	});
	return anchor ? sliceSection({ markdown, anchor, url }) : markdown;
};

// `<part file="…" />` → a sibling content file, resolved next to its document.
const contentFileResolver =
	(documentPath: string) =>
	(file: string): string =>
		readFileSync(resolve(contentRoot, dirname(documentPath), file), "utf8");

const mcpResources: McpResource[] = [];
const skills: Skill[] = [];
const skillNameByEntryKey: Record<string, string> = {};

for (const [entryKey, entry] of Object.entries(config)) {
	if (entry.formats.mcp) {
		const mcp = entry.formats.mcp;
		const ownTitle = Boolean(mcp.document);
		const body = mcp.document
			? composeDocument({
					path: mcp.document,
					text: readFileSync(resolve(contentRoot, mcp.document), "utf8"),
					resolveContentFile: contentFileResolver(mcp.document),
					resolveDocs,
				})
			: composeSources({ sources: mcp.sources ?? [], readSource });
		mcpResources.push(
			toMcpResource({
				title: entry.title,
				description: entry.description,
				format: mcp,
				body,
				ownTitle,
			}),
		);
	}
	if (entry.formats.skill) {
		const { file } = entry.formats.skill;
		const skill = composeSkill({
			path: file,
			text: readFileSync(resolve(contentRoot, file), "utf8"),
			resolveDocs,
			resolveContentFile: contentFileResolver(file),
		});
		skillNameByEntryKey[entryKey] = skill.name;
		skills.push(toSkill({ skill }));
	}
}

const banner = `// AUTO-GENERATED by scripts/generate.ts — do not edit by hand.
// Canonical source: apps/docs/** and content/**. Run \`bun run gen\` to regenerate.`;

const writeGenerated = ({
	file,
	typeName,
	typeImport,
	value,
}: {
	file: string;
	typeName: string;
	typeImport: string;
	value: unknown;
}) => {
	const outPath = resolve(here, "../src/generated", file);
	mkdirSync(dirname(outPath), { recursive: true });
	writeFileSync(
		outPath,
		`${banner}\n\n${typeImport}\n\nexport const ${typeName} = ${JSON.stringify(value, null, 2)};\n`,
	);
	process.stdout.write(`Wrote ${outPath}\n`);
};

// Recursively inline `<part file="…" />` (relative to each file) so each
// surface prompt + the MCP instructions compose the shared personality +
// autumn-rules core DRY.
const PROMPT_PART = /<part\s+file="([^"]+)"\s*\/>/g;
const composePrompt = (relPath: string): string =>
	readFileSync(resolve(contentRoot, relPath), "utf8")
		.replace(PROMPT_PART, (_match, file: string) =>
			composePrompt(join(dirname(relPath), file)).trim(),
		)
		.replace(/\n{3,}/g, "\n\n")
		.trim();

writeGenerated({
	file: "instructions.generated.ts",
	typeName: "autumnMcpInstructions: string",
	typeImport: "",
	value: composePrompt("instructions/mcp.md"),
});

writeGenerated({
	file: "leaf-prompts.generated.ts",
	typeName: 'leafPrompts: Record<"dashboard" | "slack", string>',
	typeImport: "",
	value: {
		dashboard: composePrompt("instructions/dashboard.md"),
		slack: composePrompt("instructions/slack.md"),
	},
});

const agentIds = Object.keys(agents) as (keyof typeof agents)[];
const agentIdUnion = agentIds.map((id) => `"${id}"`).join(" | ");

const resolveAgentSkillNames = (skillKeys: string[]): string[] =>
	skillKeys.map((key) => {
		const name = skillNameByEntryKey[key];
		if (!name) {
			throw new Error(`Agent skill key "${key}" has no skill format in config`);
		}
		return name;
	});

const leafAgentPrompts = Object.fromEntries(
	agentIds.map((id) => [id, composePrompt(agents[id].instructions)]),
);
const leafAgentSkillNames = Object.fromEntries(
	agentIds.map((id) => [id, resolveAgentSkillNames(agents[id].skills)]),
);
const leafSkillRequires = Object.fromEntries(
	skills.map((skill) => [skill.name, skill.requires ?? []]),
);

const writeGeneratedModule = ({
	declarations,
	file,
}: {
	declarations: string[];
	file: string;
}) => {
	const outPath = resolve(here, "../src/generated", file);
	mkdirSync(dirname(outPath), { recursive: true });
	writeFileSync(outPath, `${banner}\n\n${declarations.join("\n\n")}\n`);
	process.stdout.write(`Wrote ${outPath}\n`);
};

writeGeneratedModule({
	declarations: [
		`export const leafAgentPrompts: Record<${agentIdUnion}, string> = ${JSON.stringify(leafAgentPrompts, null, 2)};`,
		`export const leafAgentSkillNames: Record<${agentIdUnion}, string[]> = ${JSON.stringify(leafAgentSkillNames, null, 2)};`,
		`export const leafSkillRequires: Record<string, string[]> = ${JSON.stringify(leafSkillRequires, null, 2)};`,
	],
	file: "agent-prompts.generated.ts",
});
writeGenerated({
	file: "mcp-resources.generated.ts",
	typeName: "mcpResources: McpResource[]",
	typeImport:
		'import type { McpResource } from "../translate/formats/types.js";',
	value: mcpResources,
});
writeGenerated({
	file: "skills.generated.ts",
	typeName: "skills: Skill[]",
	typeImport: 'import type { Skill } from "../translate/formats/types.js";',
	// requires ships via agent-prompts.generated.ts; omitting it here keeps this
	// artifact byte-stable for consumers that only bundle skill files.
	value: skills.map(({ requires, ...skill }) => skill),
});

// Readable rendered artifacts (human-inspectable; runtime imports the .ts above).
const readableRoot = resolve(here, "../generated");

const writeReadable = ({
	relPath,
	contents,
}: {
	relPath: string;
	contents: string;
}) => {
	const outPath = resolve(readableRoot, relPath);
	mkdirSync(dirname(outPath), { recursive: true });
	writeFileSync(outPath, contents.endsWith("\n") ? contents : `${contents}\n`);
	process.stdout.write(`Wrote ${outPath}\n`);
};

for (const resource of mcpResources) {
	writeReadable({
		relPath: `mcp/${resource.name}.md`,
		contents: resource.text,
	});
}
writePublicSkills({
	outputDirectory: resolve(readableRoot, "skills"),
	skills,
});
for (const id of agentIds) {
	writeReadable({
		relPath: `agents/${id}.md`,
		contents: leafAgentPrompts[id],
	});
}

// useautumn.com/SKILL.md — the one URL the dashboard's setup prompt points an
// agent at. References inline because a single fetch can't follow them.
const SETUP_SKILL_NAME = "autumn-setup";
const setupSkill = skills.find((skill) => skill.name === SETUP_SKILL_NAME);
if (!setupSkill) {
	throw new Error(
		`Missing "${SETUP_SKILL_NAME}" skill for the website SKILL.md`,
	);
}

const websiteSkillPath = resolve(here, "../../../apps/website/public/SKILL.md");
writeFileSync(
	websiteSkillPath,
	`${[
		setupSkill.markdown.trim(),
		...setupSkill.references.map(
			(reference) => `## ${reference.path}\n\n${reference.contents.trim()}`,
		),
	].join("\n\n")}\n`,
);
process.stdout.write(`Wrote ${websiteSkillPath}\n`);
