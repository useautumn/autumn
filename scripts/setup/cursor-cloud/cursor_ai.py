#!/usr/bin/env python3
"""Cursor Cloud post-processing for ai-sync output.

`bun ai sync` writes:
  - `.cursor/skills/<name>` as **symlinks** into `ai/config/skills/**`
  - `.cursor/mcp.json` **without** Executor's Authorization header when
    EXECUTOR_API_KEY is unset (ai-sync drops `${env:VAR}` headers so laptop
    OAuth still works)

Cursor Cloud slash commands index real files (and `~/.cursor/skills`), not
gitignored symlinks — same class of bug as Devin, which is why `bun sync
devin` copies instead of linking. Executor cannot do interactive OAuth on
a headless VM; the Infisical `EXECUTOR_API_KEY` has to land in mcp.json.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import stat
import sys
from pathlib import Path

EXECUTOR_URL = "https://executor.sh/mcp"
ENV_PLACEHOLDER = "Bearer ${env:EXECUTOR_API_KEY}"

AGENTS_BEGIN = "<!-- cursor-cloud-specific-instructions -->"
AGENTS_END = "<!-- /cursor-cloud-specific-instructions -->"

AGENTS_CLOUD_SECTION = f"""
{AGENTS_BEGIN}

## Cursor Cloud specific instructions

Skills are generated by `bun ai sync` into `.cursor/skills`, which is gitignored.
ai-sync creates **symlinks** into the `ai` submodule; Cursor Cloud slash commands
do not follow those, so Cloud install/start **copies** each skill (and into
`~/.cursor/skills`). After boot you should have `/tdd` and `/autumn-tdd-test`.
`tdd` is current and supersedes `autumn-tdd-test` — if the user invokes the old
name, still load `.cursor/skills/autumn-tdd-test/SKILL.md` (or `tdd` if they
asked for TDD in general).

Executor MCP (`https://executor.sh/mcp`) is the front door for external tools.
`start` pulls `EXECUTOR_API_KEY` from Infisical (or a Team Runtime Secret of the
same name) and writes the Bearer header into `.cursor/mcp.json`. Do not try
interactive OAuth. If executor tools are missing, say so rather than substituting
Axiom/PlanetScale OAuth servers.

Boot does **not** start `bun dw`. Run it when the task needs the app. Infisical,
ports, and stripe listen notes live in `CURSOR.md` (not auto-loaded — this
section is). The in-IDE Browser tab stays blank (Cursor bug, any URL) — open
`http://localhost:3000` from Ports in Chrome/Safari, or the ngrok URL.

{AGENTS_END}
""".lstrip()


def _chmod_private(path: Path) -> None:
	path.chmod(stat.S_IRUSR | stat.S_IWUSR)


def materialize_skills(
	*,
	root: Path,
	user_skills_dir: Path,
) -> dict[str, int]:
	"""Replace `.cursor/skills` symlinks with real directories and mirror them."""
	skills_dir = root / ".cursor" / "skills"
	skills_dir.mkdir(parents=True, exist_ok=True)
	copied = 0
	already = 0
	errors = 0

	for entry in sorted(skills_dir.iterdir()):
		if entry.name.startswith("."):
			continue
		try:
			if entry.is_symlink():
				target = entry.resolve()
				if not target.exists():
					print(
						f"[cursor-ai] skip broken skill symlink {entry.name} -> {target}",
						file=sys.stderr,
					)
					errors += 1
					continue
				entry.unlink()
				shutil.copytree(target, entry, symlinks=False, dirs_exist_ok=False)
				copied += 1
			elif entry.is_dir():
				already += 1
			else:
				continue
		except OSError as err:
			print(f"[cursor-ai] {entry.name}: {err}", file=sys.stderr)
			errors += 1

	user_skills_dir.mkdir(parents=True, exist_ok=True)
	mirrored = 0
	for entry in sorted(skills_dir.iterdir()):
		if entry.name.startswith(".") or not entry.is_dir():
			continue
		dest = user_skills_dir / entry.name
		if dest.exists():
			shutil.rmtree(dest)
		shutil.copytree(entry, dest, symlinks=False)
		mirrored += 1

	print(
		f"[cursor-ai] skills: copied={copied} already_real={already} "
		f"mirrored_to_user={mirrored} errors={errors}"
	)
	for name in ("tdd", "autumn-tdd-test"):
		skill_md = skills_dir / name / "SKILL.md"
		kind = "missing"
		if skill_md.is_file() and not skill_md.is_symlink():
			kind = "file"
		elif (skills_dir / name).is_symlink():
			kind = "symlink"
		print(f"[cursor-ai] skill {name}: {kind}")

	return {
		"copied": copied,
		"already": already,
		"mirrored": mirrored,
		"errors": errors,
	}


def _executor_entry(*, authorization: str) -> dict[str, object]:
	return {
		"url": EXECUTOR_URL,
		"headers": {"Authorization": authorization},
	}


def write_mcp_json(
	*,
	root: Path,
	user_mcp_path: Path,
	authorization: str,
) -> None:
	"""Write project + user mcp.json. `authorization` is the full Bearer value."""
	cursor_dir = root / ".cursor"
	cursor_dir.mkdir(parents=True, exist_ok=True)
	path = cursor_dir / "mcp.json"

	data: dict[str, object] = {"mcpServers": {}}
	if path.exists():
		try:
			loaded = json.loads(path.read_text(encoding="utf-8"))
			if isinstance(loaded, dict):
				data = loaded
		except json.JSONDecodeError:
			print("[cursor-ai] existing .cursor/mcp.json was invalid; rewriting", file=sys.stderr)

	servers = data.get("mcpServers")
	if not isinstance(servers, dict):
		servers = {}
		data["mcpServers"] = servers

	existing = servers.get("executor")
	merged: dict[str, object] = {"url": EXECUTOR_URL}
	if isinstance(existing, dict):
		merged.update(existing)
	merged["url"] = EXECUTOR_URL
	merged["headers"] = {"Authorization": authorization}
	# Cloud cannot complete OAuth; a leftover oauth block would fight the header.
	merged.pop("oauth", None)
	servers["executor"] = merged

	text = json.dumps(data, indent="\t") + "\n"
	path.write_text(text, encoding="utf-8")
	_chmod_private(path)

	user_mcp_path.parent.mkdir(parents=True, exist_ok=True)
	user_mcp_path.write_text(text, encoding="utf-8")
	_chmod_private(user_mcp_path)

	has_placeholder = "${env:EXECUTOR_API_KEY}" in authorization
	print(
		"[cursor-ai] executor MCP: wrote Authorization header "
		f"({'env interpolation' if has_placeholder else 'bearer from env'}) "
		f"to {path} and {user_mcp_path}"
	)


def append_agents_cloud_section(*, root: Path) -> None:
	path = root / "AGENTS.md"
	existing = path.read_text(encoding="utf-8") if path.exists() else ""
	if AGENTS_BEGIN in existing and AGENTS_END in existing:
		before = existing.split(AGENTS_BEGIN, 1)[0].rstrip()
		after = existing.split(AGENTS_END, 1)[1].lstrip()
		text = (
			before
			+ ("\n\n" if before else "")
			+ AGENTS_CLOUD_SECTION
			+ ("\n" + after if after else "")
		)
		if not text.endswith("\n"):
			text += "\n"
	else:
		text = existing.rstrip() + ("\n\n" if existing.strip() else "") + AGENTS_CLOUD_SECTION
		if not text.endswith("\n"):
			text += "\n"
	path.write_text(text, encoding="utf-8")
	print(f"[cursor-ai] wrote Cursor Cloud section to {path}")


def main(argv: list[str] | None = None) -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--root", type=Path, default=Path.cwd())
	parser.add_argument(
		"--user-skills",
		type=Path,
		default=Path.home() / ".cursor" / "skills",
	)
	parser.add_argument(
		"--user-mcp",
		type=Path,
		default=Path.home() / ".cursor" / "mcp.json",
	)
	sub = parser.add_subparsers(dest="cmd", required=True)
	sub.add_parser("materialize", help="Copy skill symlinks to real dirs")
	sub.add_parser("mcp-template", help="Write executor MCP with ${env:EXECUTOR_API_KEY}")
	sub.add_parser("mcp-inject", help="Write executor MCP with EXECUTOR_API_KEY from env")
	sub.add_parser("agents-md", help="Append Cursor Cloud section to AGENTS.md")
	args = parser.parse_args(argv)
	root = args.root.resolve()

	if args.cmd == "materialize":
		result = materialize_skills(root=root, user_skills_dir=args.user_skills)
		return 1 if result["errors"] else 0

	if args.cmd == "mcp-template":
		write_mcp_json(
			root=root,
			user_mcp_path=args.user_mcp,
			authorization=ENV_PLACEHOLDER,
		)
		return 0

	if args.cmd == "mcp-inject":
		key = os.environ.get("EXECUTOR_API_KEY", "").strip()
		if not key:
			print(
				"[cursor-ai] mcp-inject: EXECUTOR_API_KEY is empty; writing env interpolation",
				file=sys.stderr,
			)
			write_mcp_json(
				root=root,
				user_mcp_path=args.user_mcp,
				authorization=ENV_PLACEHOLDER,
			)
			return 1
		write_mcp_json(
			root=root,
			user_mcp_path=args.user_mcp,
			authorization=f"Bearer {key}",
		)
		return 0

	if args.cmd == "agents-md":
		append_agents_cloud_section(root=root)
		return 0

	return 2


if __name__ == "__main__":
	raise SystemExit(main())
