#!/usr/bin/env bash
# Cursor Cloud `start` — per-boot. Local infra via bun dw setup.
# Infisical: persist Cursor's INFISICAL_TOKEN (Token Auth) into env.sh / cache.
# No `infisical login`. Does not wrap node_modules/.bin/infisical.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$ROOT"
export PATH="$ROOT/node_modules/.bin:/usr/local/bin:$HOME/.bun/bin:$PATH"

export DW_HEADLESS=1
append_once() {
	local file="$1"
	local line="$2"
	touch "$file"
	grep -qxF "$line" "$file" 2>/dev/null || echo "$line" >>"$file"
}

append_once "${HOME}/.bashrc" 'export DW_HEADLESS=1'

env_sh="${HOME}/.autumn-agent/env.sh"
mkdir -p "${HOME}/.autumn-agent"

# Token Auth access token from Cursor. Persist so later shells that miss
# Runtime Secrets can still `infisical run`. No universal-auth login.
if [ -n "${INFISICAL_TOKEN:-}" ]; then
	mkdir -p "${HOME}/.cache"
	printf '%s' "$INFISICAL_TOKEN" > "${HOME}/.cache/autumn-infisical-token"
	chmod 600 "${HOME}/.cache/autumn-infisical-token"
	echo "[cursor-cloud-start] Infisical token ready"
else
	echo "[cursor-cloud-start] INFISICAL_TOKEN unset — set it as a Team Runtime Secret"
	echo "[cursor-cloud-start] (machine identity → Token Auth → Create Token)."
	echo "[cursor-cloud-start] Repo .cursor/environment.json wins over the team env — Team-scoped secrets, not Environment."
fi

cat > "$env_sh" <<ENVSH
# Generated by scripts/setup/cursor-cloud/start.sh — sourced from bashrc / BASH_ENV / zshenv.
export DW_HEADLESS=1
export PATH="${ROOT}/node_modules/.bin:/usr/local/bin:\$HOME/.bun/bin:\$PATH"
if [ -z "\${INFISICAL_TOKEN:-}" ] && [ -s "\${HOME}/.cache/autumn-infisical-token" ]; then
  INFISICAL_TOKEN="\$(cat "\${HOME}/.cache/autumn-infisical-token")"
  export INFISICAL_TOKEN
fi
if [ -z "\${INFISICAL_PROJECT_ID:-}" ] && [ -f "${ROOT}/.infisical.json" ]; then
  INFISICAL_PROJECT_ID="\$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("workspaceId") or "")' "${ROOT}/.infisical.json" 2>/dev/null || true)"
  [ -n "\$INFISICAL_PROJECT_ID" ] && export INFISICAL_PROJECT_ID
fi
if [ -f "${ROOT}/scripts/setup/cursor-cloud/isolation.env" ]; then
  set -a
  # shellcheck disable=SC1091
  . "${ROOT}/scripts/setup/cursor-cloud/isolation.env"
  set +a
fi
unset NEON_WORKTREE_API_KEY
unset MISC_CACHE_DRAGONFLY_PRIVATE_URL
unset CACHE_BACKUP_URL
ENVSH
chmod 600 "$env_sh"

append_once "${HOME}/.bashrc" ". ${env_sh}"
append_once "${HOME}/.bashrc" "export BASH_ENV=${env_sh}"
append_once "${HOME}/.profile" ". ${env_sh}"
if [ -n "${ZDOTDIR:-}" ]; then
	append_once "${ZDOTDIR}/.zshenv" ". ${env_sh}"
else
	append_once "${HOME}/.zshenv" ". ${env_sh}"
fi
export BASH_ENV="$env_sh"
# Current start process (and anything it execs) should see Infisical too.
# shellcheck disable=SC1090
. "$env_sh"

BUN="${HOME}/.bun/bin/bun"
if [ ! -x "$BUN" ]; then
	BUN="$(command -v bun || true)"
fi
if [ -f ai/package.json ] && [ -n "$BUN" ]; then
	if [ ! -f "${HOME}/.cursor/skills/tdd/SKILL.md" ]; then
		echo "[cursor-cloud-start] ~/.cursor/skills missing — running bun ai sync --copy"
		"$BUN" ai/src/cli.ts sync --copy || echo "[cursor-cloud-start] bun ai sync failed (skills may be missing)"
	fi
	"$BUN" "$ROOT/scripts/setup/cursor-cloud/cursorCloud.ts" agents-md || true
fi
if [ -z "${EXECUTOR_API_KEY:-}" ] && command -v infisical >/dev/null 2>&1; then
	set +e
	pulled="$(infisical run --env=dev --recursive --silent -- printenv EXECUTOR_API_KEY 2>/dev/null)"
	st=$?
	set -e
	if [ "$st" -eq 0 ]; then
		pulled="${pulled%%$'\n'*}"
		[ -n "$pulled" ] && export EXECUTOR_API_KEY="$pulled"
	fi
fi
if [ -n "${EXECUTOR_API_KEY:-}" ]; then
	grep -v '^export EXECUTOR_API_KEY=' "$env_sh" >"${env_sh}.tmp" || true
	mv "${env_sh}.tmp" "$env_sh"
	printf 'export EXECUTOR_API_KEY=%q\n' "$EXECUTOR_API_KEY" >>"$env_sh"
	chmod 600 "$env_sh"
fi
if [ -n "$BUN" ]; then
	"$BUN" "$ROOT/scripts/setup/cursor-cloud/cursorCloud.ts" mcp || \
		echo "[cursor-cloud-start] executor MCP configure failed (non-fatal)"
fi
# shellcheck disable=SC1090
. "$env_sh"

# NGROK_AUTHTOKEN: Team Runtime Secret or Infisical. Never log the value.
if [ -z "${NGROK_AUTHTOKEN:-}" ] && command -v infisical >/dev/null 2>&1; then
	set +e
	ngrok_tok="$(infisical run --env=dev --recursive --silent -- printenv NGROK_AUTHTOKEN 2>/dev/null)"
	st=$?
	set -e
	if [ "$st" -eq 0 ]; then
		ngrok_tok="${ngrok_tok%%$'\n'*}"
		if [ -n "$ngrok_tok" ]; then
			export NGROK_AUTHTOKEN="$ngrok_tok"
		fi
	fi
fi
if [ -n "${NGROK_AUTHTOKEN:-}" ]; then
	grep -v '^export NGROK_AUTHTOKEN=' "$env_sh" >"${env_sh}.tmp" || true
	mv "${env_sh}.tmp" "$env_sh"
	printf 'export NGROK_AUTHTOKEN=%q\n' "$NGROK_AUTHTOKEN" >>"$env_sh"
	chmod 600 "$env_sh"
	echo "[cursor-cloud-start] NGROK_AUTHTOKEN ready (len=${#NGROK_AUTHTOKEN})"
else
	echo "[cursor-cloud-start] NGROK_AUTHTOKEN unset — bun dw setup will skip the public tunnel."
fi
# shellcheck disable=SC1090
. "$env_sh"

# Infra + one ngrok hostname. Does not start the app.
if [ -n "$BUN" ]; then
	echo "[cursor-cloud-start] bun dw setup (local infra + public URL)"
	"$BUN" dw setup || echo "[cursor-cloud-start] bun dw setup failed (non-fatal)"
fi
