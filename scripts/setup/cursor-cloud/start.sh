#!/usr/bin/env bash
# Cursor Cloud `start` — per-boot. Starts local Postgres/Redis/ClickHouse/ElasticMQ,
# mints Infisical token from machine identity, writes server/.env isolation overlay.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$ROOT"
export PATH="$ROOT/node_modules/.bin:/usr/local/bin:$HOME/.bun/bin:$PATH"
bash "$ROOT/scripts/setup/cursor-cloud/wrap-infisical-bin.sh"

export DW_HEADLESS=1
append_once() {
	local file="$1"
	local line="$2"
	touch "$file"
	grep -qxF "$line" "$file" 2>/dev/null || echo "$line" >>"$file"
}

append_once "${HOME}/.bashrc" 'export DW_HEADLESS=1'

env_sh="${HOME}/.autumn-agent/env.sh"
mkdir -p "${HOME}/.autumn-agent"

# Cursor injects INFISICAL_CLIENT_ID/SECRET into every process. Infisical CLI
# `run` still needs INFISICAL_TOKEN (see infisical-machine-login.sh). Mint once
# here so start's own children have it; the node_modules/.bin shim covers bun dw.
if [ -n "${INFISICAL_CLIENT_ID:-}" ] && [ -z "${INFISICAL_UNIVERSAL_AUTH_CLIENT_ID:-}" ]; then
	export INFISICAL_UNIVERSAL_AUTH_CLIENT_ID="$INFISICAL_CLIENT_ID"
	export INFISICAL_UNIVERSAL_AUTH_CLIENT_SECRET="${INFISICAL_CLIENT_SECRET:-}"
fi
if token="$(bash "$ROOT/scripts/setup/cursor-cloud/infisical-machine-login.sh")"; then
	export INFISICAL_TOKEN="$token"
	mkdir -p "${HOME}/.cache"
	printf '%s' "$token" > "${HOME}/.cache/autumn-infisical-token"
	chmod 600 "${HOME}/.cache/autumn-infisical-token"
	echo "[cursor-cloud-start] Infisical machine identity: token ready"
else
	echo "[cursor-cloud-start] Infisical machine identity not configured (INFISICAL_CLIENT_ID/SECRET unset in start)"
	echo "[cursor-cloud-start] Add them as Environment Runtime Secrets — do not paste into chat."
	echo "[cursor-cloud-start] bun dw will fail until start can mint INFISICAL_TOKEN."
fi

cat > "$env_sh" <<ENVSH
# Generated by scripts/setup/cursor-cloud/start.sh — sourced from bashrc / BASH_ENV / zshenv.
export DW_HEADLESS=1
export PATH="${ROOT}/node_modules/.bin:/usr/local/bin:\$HOME/.bun/bin:\$PATH"
if [ -n "\${INFISICAL_CLIENT_ID:-}" ]; then
  export INFISICAL_UNIVERSAL_AUTH_CLIENT_ID="\${INFISICAL_UNIVERSAL_AUTH_CLIENT_ID:-\$INFISICAL_CLIENT_ID}"
  export INFISICAL_UNIVERSAL_AUTH_CLIENT_SECRET="\${INFISICAL_UNIVERSAL_AUTH_CLIENT_SECRET:-\${INFISICAL_CLIENT_SECRET:-}}"
fi
if [ -z "\${INFISICAL_TOKEN:-}" ] && [ -s "\${HOME}/.cache/autumn-infisical-token" ]; then
  INFISICAL_TOKEN="\$(cat "\${HOME}/.cache/autumn-infisical-token")"
  export INFISICAL_TOKEN
fi
if [ -z "\${INFISICAL_TOKEN:-}" ]; then
  INFISICAL_TOKEN="\$("${ROOT}/scripts/setup/cursor-cloud/infisical-machine-login.sh" 2>/dev/null || true)"
  [ -n "\$INFISICAL_TOKEN" ] && export INFISICAL_TOKEN
fi
if [ -f "${ROOT}/scripts/setup/cursor-cloud/isolation.env" ]; then
  set -a
  # shellcheck disable=SC1091
  . "${ROOT}/scripts/setup/cursor-cloud/isolation.env"
  set +a
fi
unset NEON_WORKTREE_API_KEY
ENVSH
chmod 600 "$env_sh"

append_once "${HOME}/.bashrc" ". ${env_sh}"
append_once "${HOME}/.bashrc" "export BASH_ENV=${env_sh}"
append_once "${HOME}/.profile" ". ${env_sh}"
if [ -n "${ZDOTDIR:-}" ]; then
	append_once "${ZDOTDIR}/.zshenv" ". ${env_sh}"
else
	append_once "${HOME}/.zshenv" ". ${env_sh}"
fi
export BASH_ENV="$env_sh"
# Current start process (and anything it execs) should see Infisical too.
# shellcheck disable=SC1090
. "$env_sh"

bash scripts/setup/agent-services.sh
