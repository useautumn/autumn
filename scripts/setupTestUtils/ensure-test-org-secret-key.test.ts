import { afterEach, beforeEach, describe, expect, mock, test } from "bun:test";

const realApiKeyUtils = await import(
	"@server/internal/dev/apiKeys/apiKeyUtils.js"
);
const realRepos = await import("@server/internal/dev/repos/index.js");
const createKey = mock(async () => "am_sk_test_generated");
const createHardcodedKey = mock(async () => ({
	key: "am_sk_test_configured",
	alreadyExists: true,
}));
const listByOrg = mock(async () => [
	{
		id: "key_stale",
		name: "Unit Test Key",
		meta: { autogenerated: true },
	},
	{
		id: "key_preserved",
		name: "Other Key",
		meta: { autogenerated: true },
	},
]);
const deleteKey = mock(async () => []);

mock.module("@server/internal/dev/apiKeys/apiKeyUtils.js", () => ({
	...realApiKeyUtils,
	ApiKeyPrefix: { Sandbox: "am_sk_test" },
	createHardcodedKey,
	createKey,
}));
mock.module("@server/internal/dev/repos/index.js", () => ({
	...realRepos,
	apiKeyRepo: {
		...realRepos.apiKeyRepo,
		delete: deleteKey,
		listByOrg,
	},
}));

const { ensureTestOrgSecretKey } = await import("./ensureTestOrgSecretKey.js");

const createDb = ({ orgExists = true }: { orgExists?: boolean } = {}) =>
	({
		query: {
			organizations: {
				findFirst: async () =>
					orgExists ? { id: "org_2sWv2S8LJ9iaTjLI6UtNsfL88Kt" } : undefined,
			},
		},
	}) as never;

describe("ensureTestOrgSecretKey", () => {
	beforeEach(() => {
		delete process.env.UNIT_TEST_AUTUMN_SECRET_KEY;
		createKey.mockClear();
		createHardcodedKey.mockClear();
		listByOrg.mockClear();
		deleteKey.mockClear();
	});

	afterEach(() => {
		delete process.env.UNIT_TEST_AUTUMN_SECRET_KEY;
	});

	test("generates a key when no configured key exists", async () => {
		const result = await ensureTestOrgSecretKey({ db: createDb() });

		expect(result).toEqual({
			key: "am_sk_test_generated",
			alreadyExists: false,
			generated: true,
		});
		expect(deleteKey).toHaveBeenCalledWith({
			db: expect.anything(),
			id: "key_stale",
			orgId: "org_2sWv2S8LJ9iaTjLI6UtNsfL88Kt",
		});
		expect(deleteKey).toHaveBeenCalledTimes(1);
		expect(createKey).toHaveBeenCalledTimes(1);
		expect(createKey.mock.calls[0]?.[0]).toMatchObject({
			env: "sandbox",
			name: "Unit Test Key",
			orgId: "org_2sWv2S8LJ9iaTjLI6UtNsfL88Kt",
			prefix: "am_sk_test",
			meta: { autogenerated: true },
		});
		expect(createHardcodedKey).not.toHaveBeenCalled();
	});

	test("ensures the configured key when one is available", async () => {
		process.env.UNIT_TEST_AUTUMN_SECRET_KEY = "am_sk_test_configured";

		const result = await ensureTestOrgSecretKey({ db: createDb() });

		expect(result).toEqual({
			key: "am_sk_test_configured",
			alreadyExists: true,
			generated: false,
		});
		expect(createHardcodedKey).toHaveBeenCalledWith(
			expect.objectContaining({ hardcodedKey: "am_sk_test_configured" }),
		);
		expect(createKey).not.toHaveBeenCalled();
		expect(listByOrg).not.toHaveBeenCalled();
	});

	test("rejects a missing test organization before creating a key", async () => {
		await expect(
			ensureTestOrgSecretKey({ db: createDb({ orgExists: false }) }),
		).rejects.toThrow("Test org 'unit-test-org'");
		expect(createKey).not.toHaveBeenCalled();
		expect(createHardcodedKey).not.toHaveBeenCalled();
	});
});
