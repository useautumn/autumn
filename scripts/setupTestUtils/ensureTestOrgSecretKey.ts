import { AppEnv, organizations } from "@autumn/shared";
import type { DrizzleCli } from "@server/db/initDrizzle.js";
import {
	ApiKeyPrefix,
	createHardcodedKey,
	createKey,
} from "@server/internal/dev/apiKeys/apiKeyUtils.js";
import chalk from "chalk";
import { eq } from "drizzle-orm";
import { TEST_ORG_CONFIG } from "./createTestOrg.js";

/** Ensures a usable shared test-org key without clearing products or features. */
export async function ensureTestOrgSecretKey({
	db,
}: {
	db: DrizzleCli;
}): Promise<{ key: string; alreadyExists: boolean }> {
	const org = await db.query.organizations.findFirst({
		where: eq(organizations.id, TEST_ORG_CONFIG.id),
	});
	if (!org) {
		throw new Error(
			`Test org '${TEST_ORG_CONFIG.slug}' (${TEST_ORG_CONFIG.id}) is missing. ` +
				"Run full setup first: bun setup:test --yes",
		);
	}
	const hardcodedKey = process.env.UNIT_TEST_AUTUMN_SECRET_KEY?.trim();
	if (!hardcodedKey) {
		const key = await createKey({
			db,
			env: AppEnv.Sandbox,
			name: "Unit Test Key",
			orgId: TEST_ORG_CONFIG.id,
			prefix: ApiKeyPrefix.Sandbox,
			meta: {
				createdBy: "ensure-test-org-secret-key",
				createdAt: new Date().toISOString(),
				autogenerated: true,
			},
		});
		console.log(chalk.greenBright("✅ Generated fresh test org API key"));
		return { key, alreadyExists: false };
	}

	const result = await createHardcodedKey({
		db,
		env: AppEnv.Sandbox,
		name: "Unit Test Key",
		orgId: TEST_ORG_CONFIG.id,
		hardcodedKey,
		meta: {
			createdBy: "ensure-test-org-secret-key",
			createdAt: new Date().toISOString(),
		},
	});

	console.log(
		chalk.greenBright(
			result.alreadyExists
				? "✅ Test org API key already present in database"
				: "✅ Inserted test org API key into database",
		),
	);

	return result;
}
